# v7-compatible cache files store media URLs once, instead of repeating them in
# every role/shot table. Older lb_cache.rds files with img_url/team_logo_url
# columns still work.
lb_media_lookup <- NULL
if (!is.null(lb_cache_precomputed) && !is.null(lb_cache_precomputed$media_lookup)) {
