# Lightweight leaderboard tooltip. This is intentionally much simpler than the
# scatterplot image overlay: no gray-out, no Plotly.restyle calls, and no row
# image layer. It only shows one hover card with an optional local headshot/logo.
add_leaderboard_hover_tooltip <- function(p) {
  htmlwidgets::onRender(
    p,
    "function(el, x) {
      function getGd() { return document.getElementById(el.id); }
      function ensureTip() {
        var tip = document.getElementById('epaa-lb-hover-tooltip-global');
        if (!tip) {
          tip = document.createElement('div');
          tip.id = 'epaa-lb-hover-tooltip-global';
          tip.className = 'epaa-lb-hover-tooltip';
          tip.style.position = 'fixed';
          tip.style.zIndex = '2147483647';
          tip.style.pointerEvents = 'none';
          tip.style.display = 'none';
          tip.style.maxWidth = '300px';
          tip.style.padding = '8px 9px';
          tip.style.border = '1px solid #6d28d9';
          tip.style.background = '#0a0a14';
          tip.style.color = '#e8e8ef';
          tip.style.fontFamily = 'Inter, system-ui, sans-serif';
          tip.style.fontSize = '12px';
          tip.style.fontWeight = '500';
          tip.style.lineHeight = '1.25';
          tip.style.boxShadow = '0 12px 22px rgba(0,0,0,0.45)';
          tip.style.overflow = 'visible';
          document.body.appendChild(tip);
        }
        return tip;
      }
      function rawPointText(pt) {
        if (!pt) return '';
        if (pt.text != null) return String(pt.text);
        if (pt.hovertext != null) return String(pt.hovertext);
        if (pt.data && Array.isArray(pt.data.text)) return String(pt.data.text[pt.pointNumber] || '');
        if (pt.fullData && Array.isArray(pt.fullData.text)) return String(pt.fullData.text[pt.pointNumber] || '');
        return '';
      }
      function pointText(pt) {
        return rawPointText(pt).replace(/<!--EPAA_IMG:[\\s\\S]*?-->/g, '');
      }
      function pointImage(pt) {
        if (!pt) return '';
        var cd = pt.customdata;
        if (Array.isArray(cd)) cd = cd[0];
        if ((cd == null || cd === '') && pt.data && Array.isArray(pt.data.customdata)) {
          cd = pt.data.customdata[pt.pointNumber];
          if (Array.isArray(cd)) cd = cd[0];
        }
        if ((cd == null || cd === '') && pt.fullData && Array.isArray(pt.fullData.customdata)) {
          cd = pt.fullData.customdata[pt.pointNumber];
          if (Array.isArray(cd)) cd = cd[0];
        }
        if (cd == null || String(cd) === '') {
          var m = rawPointText(pt).match(/<!--EPAA_IMG:([\\s\\S]*?)-->/);
          if (m && m[1]) cd = m[1];
        }
        if (cd == null) cd = '';
        var out = String(cd);
        if (out.indexOf('www/') === 0) out = out.substring(4);
        if (out.indexOf('www\\\\') === 0) out = out.substring(4);
        while (out.charAt(0) === '/' || out.charAt(0) === '\\\\') out = out.substring(1);
        return out;
      }
      function suppressNativeHover(gd) {
        var hover = gd.querySelector('.hoverlayer');
        if (hover) {
          hover.style.opacity = '0';
          hover.style.pointerEvents = 'none';
        }
      }
      function pointClientPosition(gd, pt, evt) {
        if (evt && evt.clientX != null && evt.clientY != null) {
          return {x: evt.clientX, y: evt.clientY};
        }
        var fl = gd._fullLayout || {};
        var rect = gd.getBoundingClientRect();
        var ml = fl.margin && fl.margin.l ? fl.margin.l : 0;
        var mt = fl.margin && fl.margin.t ? fl.margin.t : 0;
        var xpx = ml, ypx = mt;
        try {
          if (pt.xaxis && pt.x != null) xpx = ml + pt.xaxis.l2p(pt.x);
          if (pt.yaxis && pt.y != null) ypx = mt + pt.yaxis.l2p(pt.y);
        } catch(e) {}
        return {x: rect.left + xpx, y: rect.top + ypx};
      }
      function showTip(gd, pt, evt) {
        var text = pointText(pt);
        if (!text) return;
        var img = pointImage(pt);
        var tip = ensureTip();
        var imgHtml = '';
        if (img) {
          imgHtml = \"<div style='text-align:center;margin-bottom:6px;'><img src='\" + img + \"' style='width:62px;height:46px;object-fit:contain;object-position:top;' onerror='this.style.display=\\\"none\\\"'></div>\";
        }
        tip.innerHTML = imgHtml + \"<div>\" + text + \"</div><div class='epaa-lb-tip-arrow' style='position:absolute;width:0;height:0;left:50%;transform:translateX(-50%);'></div>\";
        var arrow = tip.querySelector('.epaa-lb-tip-arrow');
        tip.style.visibility = 'hidden';
        tip.style.display = 'block';
        var pos = pointClientPosition(gd, pt, evt);
        var gap = 10;
        var left = pos.x - tip.offsetWidth / 2;
        var placeAbove = (pos.y - tip.offsetHeight - gap - 10) > 0;
        var top = placeAbove ? (pos.y - tip.offsetHeight - gap) : (pos.y + gap);
        var minLeft = 8;
        var maxLeft = Math.max(8, window.innerWidth - tip.offsetWidth - 8);
        left = Math.min(Math.max(minLeft, left), maxLeft);
        if (placeAbove) {
          arrow.style.top = '100%';
          arrow.style.bottom = 'auto';
          arrow.style.borderLeft = '7px solid transparent';
          arrow.style.borderRight = '7px solid transparent';
          arrow.style.borderTop = '7px solid #6d28d9';
          arrow.style.borderBottom = '0';
        } else {
          arrow.style.bottom = '100%';
          arrow.style.top = 'auto';
          arrow.style.borderLeft = '7px solid transparent';
          arrow.style.borderRight = '7px solid transparent';
          arrow.style.borderBottom = '7px solid #6d28d9';
          arrow.style.borderTop = '0';
        }
        tip.style.left = left + 'px';
        tip.style.top = top + 'px';
        tip.style.visibility = 'visible';
        suppressNativeHover(gd);
      }
      function hideTip() {
        var tip = document.getElementById('epaa-lb-hover-tooltip-global');
        if (tip) tip.style.display = 'none';
      }
      var gd = getGd();
      if (gd) setTimeout(function(){ suppressNativeHover(gd); }, 60);
      if (gd && gd.on) {
        try {
          if (gd._epaaLbHoverHandler && gd.removeListener) gd.removeListener('plotly_hover', gd._epaaLbHoverHandler);
          if (gd._epaaLbUnhoverHandler && gd.removeListener) gd.removeListener('plotly_unhover', gd._epaaLbUnhoverHandler);
        } catch(e) {}
        gd._epaaLbHoverHandler = function(evt) {
          var pt = evt && evt.points && evt.points.length ? evt.points[0] : null;
          var mouseEvt = evt && evt.event ? evt.event : null;
          if (el._epaaLbHoverPending) cancelAnimationFrame(el._epaaLbHoverPending);
          el._epaaLbHoverPending = requestAnimationFrame(function() { showTip(gd, pt, mouseEvt); });
        };
        gd._epaaLbUnhoverHandler = function() {
          if (el._epaaLbHoverPending) cancelAnimationFrame(el._epaaLbHoverPending);
          hideTip();
        };
        gd.on('plotly_hover', gd._epaaLbHoverHandler);
        gd.on('plotly_unhover', gd._epaaLbUnhoverHandler);
      }
    }"
  )
}

# Shot grade helpers
get_grade_color <- function(pct) {
  # Red (0) → Yellow (50) → Green (100)
  if (pct <= 50) {
    r <- 255
    g <- as.integer(255 * (pct / 50))
  } else {
    r <- as.integer(255 * (1 - (pct - 50) / 50))
    g <- 255
  }
  sprintf("rgb(%d, %d, 40)", r, g)
}

get_letter_grade <- function(pct) {
  if (pct >= 90) "A"
  else if (pct >= 80) "B"
  else if (pct >= 70) "C"
  else if (pct >= 60) "D"
  else "F"
}


