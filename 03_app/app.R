attach_media_fields <- function(df, role) {
  if (is.null(df) || !nrow(df)) return(df)
  needs_media <- !all(c("img_url", "team_logo_url", "team_abbr") %in% names(df)) ||
    any(is.na(df$img_url)) || any(is.na(df$team_logo_url)) || any(is.na(df$team_abbr))
  if (!needs_media) {
    df$img_url <- if (identical(role, "team")) {
      resolve_cached_media_url_app(df$img_url, "team_logo", df$team_abbr)
    } else {
      resolve_cached_media_url_app(df$img_url, "headshot")
    }
    df$team_logo_url <- resolve_cached_media_url_app(df$team_logo_url, "team_logo", df$team_abbr)
    df$team_abbr[is.na(df$team_abbr)] <- ""
    return(df)
  }

  lookup <- NULL
  if (!is.null(lb_media_lookup) && !is.null(lb_media_lookup[[role]])) {
    lookup <- lb_media_lookup[[role]]
  }
  if (!is.null(lookup) && nrow(lookup)) {
    df <- df %>%
      left_join(lookup %>% mutate(idx = as.integer(.data$idx)), by = "idx", suffix = c("", ".lookup"))
    for (nm in c("img_url", "team_logo_url", "team_abbr")) {
      lk <- paste0(nm, ".lookup")
      if (!nm %in% names(df)) df[[nm]] <- NA_character_
      if (lk %in% names(df)) {
        miss <- is.na(df[[nm]]) | !nzchar(as.character(df[[nm]]))
        df[[nm]][miss] <- df[[lk]][miss]
        df[[lk]] <- NULL
      }
    }
  }

  # Fallback for cache objects built before media_lookup existed.
  if (!"img_url" %in% names(df)) df$img_url <- NA_character_
  if (!"team_logo_url" %in% names(df)) df$team_logo_url <- NA_character_
  if (!"team_abbr" %in% names(df)) df$team_abbr <- NA_character_
  miss_img <- is.na(df$img_url) | !nzchar(as.character(df$img_url))
  miss_team_logo <- is.na(df$team_logo_url) | !nzchar(as.character(df$team_logo_url))
  miss_team_abbr <- is.na(df$team_abbr) | !nzchar(as.character(df$team_abbr))

  if (role == "team") {
    if (any(miss_img)) df$img_url[miss_img] <- vapply(lb_meta$team$id_map[as.character(df$idx[miss_img])], get_team_logo_url, character(1))
    df$team_logo_url <- ""
    if (any(miss_team_abbr)) df$team_abbr[miss_team_abbr] <- unname(lb_meta$team$id_map[as.character(df$idx[miss_team_abbr])])
  } else {
    meta <- lb_meta[[role]]
    if (any(miss_img)) df$img_url[miss_img] <- vapply(meta$id_map[as.character(df$idx[miss_img])], get_headshot_url, character(1))
    if (role == "offense") {
      if (any(miss_team_abbr)) df$team_abbr[miss_team_abbr] <- unname(player_team_link[as.character(df$idx[miss_team_abbr])])
      if (any(miss_team_logo)) df$team_logo_url[miss_team_logo] <- unname(player_team_logo_lookup[as.character(df$idx[miss_team_logo])])
    } else {
      if (any(miss_team_abbr)) df$team_abbr[miss_team_abbr] <- unname(defender_team_abbr_lookup[as.character(df$idx[miss_team_abbr])])
      if (any(miss_team_logo)) df$team_logo_url[miss_team_logo] <- unname(defender_team_logo_lookup[as.character(df$idx[miss_team_logo])])
    }
  }

  df$img_url <- if (identical(role, "team")) {
    resolve_cached_media_url_app(df$img_url, "team_logo", df$team_abbr)
  } else {
    resolve_cached_media_url_app(df$img_url, "headshot")
  }
  df$team_logo_url <- resolve_cached_media_url_app(df$team_logo_url, "team_logo", df$team_abbr)
  df$img_url[is.na(df$img_url)] <- ""
  df$team_logo_url[is.na(df$team_logo_url)] <- ""
  df$team_abbr[is.na(df$team_abbr)] <- ""
  df
}

lb_cache_env <- new.env(parent = emptyenv())
get_lb_cache <- function(role, shot) {
  key <- paste(role, shot, sep = "__")
  if (!is.null(lb_cache_precomputed) && !is.null(lb_cache_precomputed[[key]])) {
    return(attach_media_fields(lb_cache_precomputed[[key]], role))
  }
  if (!exists(key, envir = lb_cache_env, inherits = FALSE)) {
    assign(key, build_role_shot_cache(role, shot), envir = lb_cache_env)
  }
  attach_media_fields(get(key, envir = lb_cache_env, inherits = FALSE), role)
}

# HTML overlay for image markers/logos. These are normal <img> elements drawn
# above Plotly's SVG layer so gridlines and caterpillar intervals do not show
# through player headshots. The transparent Plotly marker trace still owns hover.
add_plotly_image_overlays <- function(p, image_data) {
  htmlwidgets::onRender(
    p,
    "function(el, x, data) {
      function getGd() { return document.getElementById(el.id); }
      function getOverlay(gd) {
        var layer = gd.querySelector('.epaa-img-layer');
        if (!layer) {
          layer = document.createElement('div');
          layer.className = 'epaa-img-layer';
          layer.style.position = 'absolute';
          layer.style.left = '0';
          layer.style.top = '0';
          layer.style.right = '0';
          layer.style.bottom = '0';
          layer.style.pointerEvents = 'none';
          layer.style.zIndex = '1000';
          gd.appendChild(layer);
        }
        return layer;
      }
      function getTooltip(gd) {
        var tip = gd.querySelector('.epaa-custom-tooltip');
        if (!tip) {
          tip = document.createElement('div');
          tip.className = 'epaa-custom-tooltip';
          tip.style.position = 'absolute';
          tip.style.zIndex = '2147483647';
          tip.style.pointerEvents = 'none';
          tip.style.display = 'none';
          tip.style.maxWidth = '280px';
          tip.style.padding = '7px 9px';
          tip.style.border = '1px solid #6d28d9';
          tip.style.borderRadius = '0px';
          tip.style.background = '#0a0a14';
          tip.style.color = '#e8e8ef';
          tip.style.fontFamily = 'Inter, system-ui, sans-serif';
          tip.style.fontSize = '12px';
          tip.style.fontWeight = '500';
          tip.style.lineHeight = '1.25';
          tip.style.boxShadow = '0 12px 22px rgba(0,0,0,0.45)';
          gd.appendChild(tip);
        }
        return tip;
      }
      function suppressNativeHover(gd) {
        var hover = gd.querySelector('.hoverlayer');
        if (hover) {
          hover.style.opacity = '0';
          hover.style.pointerEvents = 'none';
        }
      }
      function pointText(pt) {
        if (!pt) return '';
        if (pt.text != null) return String(pt.text);
        if (pt.hovertext != null) return String(pt.hovertext);
        if (pt.data && Array.isArray(pt.data.text)) return String(pt.data.text[pt.pointNumber] || '');
        if (pt.fullData && Array.isArray(pt.fullData.text)) return String(pt.fullData.text[pt.pointNumber] || '');
        return '';
      }
      function keyFromPoint(pt) {
        if (!pt) return null;
        var cd = pt.customdata;
        if (Array.isArray(cd)) cd = cd[0];
        if ((cd == null || cd === '') && pt.data && Array.isArray(pt.data.customdata)) {
          cd = pt.data.customdata[pt.pointNumber];
          if (Array.isArray(cd)) cd = cd[0];
        }
        if ((cd == null || cd === '') && pt.fullData && Array.isArray(pt.fullData.customdata)) {
          cd = pt.fullData.customdata[pt.pointNumber];
          if (Array.isArray(cd)) cd = cd[0];
        }
        return cd == null ? null : String(cd);
      }
      function showTooltip(gd, pt) {
        var html = pointText(pt);
        var tip = getTooltip(gd);
        if (!html) { tip.style.display = 'none'; return; }
        var fl = gd._fullLayout || {};
        var ml = fl.margin && fl.margin.l ? fl.margin.l : 0;
        var mt = fl.margin && fl.margin.t ? fl.margin.t : 0;
        var xpx = ml, ypx = mt;
        try {
          if (pt.xaxis && pt.x != null) xpx = ml + pt.xaxis.l2p(pt.x);
          if (pt.yaxis && pt.y != null) ypx = mt + pt.yaxis.l2p(pt.y);
        } catch(e) {}
        tip.innerHTML = html;
        tip.style.zIndex = '2147483647';
        try { gd.appendChild(tip); } catch(e) {}
        tip.style.visibility = 'hidden';
        tip.style.display = 'block';
        // Keep the hover card clear of the active horizontal CI band.
        // Prefer above the point; if there is not enough room, place it below.
        var left = xpx + 16;
        var topAbove = ypx - tip.offsetHeight - 58;
        var topBelow = ypx + 58;
        var top = topAbove >= 8 ? topAbove : topBelow;
        var maxLeft = Math.max(8, gd.clientWidth - tip.offsetWidth - 8);
        var maxTop = Math.max(8, gd.clientHeight - tip.offsetHeight - 8);
        left = Math.min(Math.max(8, left), maxLeft);
        top = Math.min(Math.max(8, top), maxTop);
        tip.style.left = left + 'px';
        tip.style.top = top + 'px';
        tip.style.visibility = 'visible';
      }
      function hideTooltip(gd) {
        var tip = gd.querySelector('.epaa-custom-tooltip');
        if (tip) tip.style.display = 'none';
      }
      function shadeImages(gd, activeKey) {
        if (!gd) return;
        gd.querySelectorAll('.epaa-img-overlay').forEach(function(node) {
          var baseOpacity = node.dataset.baseOpacity || '1';
          var baseZ = parseInt(node.dataset.baseZ || '80', 10);
          if (!activeKey) {
            node.style.opacity = baseOpacity;
            node.style.filter = 'none';
            node.style.zIndex = String(baseZ);
            node.style.transform = 'scale(1)';
          } else if (node.dataset.key === String(activeKey)) {
            node.style.opacity = '1';
            node.style.filter = 'none';
            node.style.zIndex = '1800';
            node.style.transform = 'scale(1.75)';
          } else {
            node.style.opacity = '0.12';
            node.style.filter = 'grayscale(1)';
            node.style.zIndex = String(Math.max(900, baseZ - 5));
            node.style.transform = 'scale(1)';
          }
        });
      }
      function lookupActiveImageData(gd, activeKey) {
        var imgs = gd._epaaOverlayImages || [];
        for (var i = 0; i < imgs.length; i++) {
          var d = imgs[i];
          if (d && d.key != null && String(d.key) === String(activeKey) && d.lo != null && d.hi != null) return d;
        }
        return null;
      }
      function restylePlotObjects(gd, activeKey) {
        if (!gd || !gd.data || !window.Plotly) return;
        var baseIdx = [];
        var activeIdxNeg = null;
        var activeIdxPos = null;
        var lbMarkerIdx = null;
        gd.data.forEach(function(tr, i) {
          if (!tr || !tr.meta) return;
          if (tr.meta.epaaBaseSegmentTrace) baseIdx.push(i);
          if (tr.meta.epaaActiveSegmentTraceNeg) activeIdxNeg = i;
          if (tr.meta.epaaActiveSegmentTracePos) activeIdxPos = i;
          if (tr.meta.epaaLeaderboardMarkerTrace) lbMarkerIdx = i;
        });
        if (!baseIdx.length && activeIdxNeg == null && activeIdxPos == null && lbMarkerIdx == null) return;
        if (activeKey && (activeIdxNeg != null || activeIdxPos != null)) {
          var d = lookupActiveImageData(gd, activeKey);
          if (d) {
            if (baseIdx.length) window.Plotly.restyle(gd, {opacity: 0.13}, baseIdx);
            if (activeIdxNeg != null) {
              var nx0 = d.lo < 0 ? d.lo : null;
              var nx1 = d.lo < 0 ? Math.min(d.hi, 0) : null;
              var nop = (nx0 != null && nx1 != null && nx1 > nx0) ? 0.98 : 0;
              window.Plotly.restyle(gd, {
                x: [[nx0, nx1]], y: [[d.y, d.y]], opacity: nop,
                'line.color': '#ef4444', 'line.width': 5
              }, [activeIdxNeg]);
            }
            if (activeIdxPos != null) {
              var px0 = d.hi > 0 ? Math.max(d.lo, 0) : null;
              var px1 = d.hi > 0 ? d.hi : null;
              var pop = (px0 != null && px1 != null && px1 > px0) ? 0.98 : 0;
              window.Plotly.restyle(gd, {
                x: [[px0, px1]], y: [[d.y, d.y]], opacity: pop,
                'line.color': '#22c55e', 'line.width': 5
              }, [activeIdxPos]);
            }
            if (lbMarkerIdx != null) {
              var cd = gd.data[lbMarkerIdx].customdata || [];
              var op = cd.map(function(k) {
                if (Array.isArray(k)) k = k[0];
                return String(k) === String(activeKey) ? 1 : 0.18;
              });
              var sz = cd.map(function(k) {
                if (Array.isArray(k)) k = k[0];
                return String(k) === String(activeKey) ? 15 : 10;
              });
              window.Plotly.restyle(gd, {'marker.opacity': [op], 'marker.size': [sz]}, [lbMarkerIdx]);
            }
            return;
          }
        }
        if (baseIdx.length) window.Plotly.restyle(gd, {opacity: 0.82}, baseIdx);
        if (activeIdxNeg != null) window.Plotly.restyle(gd, {
          x: [[null, null]], y: [[null, null]], opacity: 0
        }, [activeIdxNeg]);
        if (activeIdxPos != null) window.Plotly.restyle(gd, {
          x: [[null, null]], y: [[null, null]], opacity: 0
        }, [activeIdxPos]);
        if (lbMarkerIdx != null) {
          var cd0 = gd.data[lbMarkerIdx].customdata || [];
          window.Plotly.restyle(gd, {
            'marker.opacity': [cd0.map(function() { return 0.96; })],
            'marker.size': [cd0.map(function() { return 12; })]
          }, [lbMarkerIdx]);
        }
      }
      function isVisibleInScroll(gd, ypx, h) {
        var scrollBox = gd.closest('.lb-scroll-plot');
        if (!scrollBox) return true;
        var buffer = 180;
        var top = gd.offsetTop + ypx - h / 2;
        var bottom = gd.offsetTop + ypx + h / 2;
        return bottom >= (scrollBox.scrollTop - buffer) && top <= (scrollBox.scrollTop + scrollBox.clientHeight + buffer);
      }
      function drawImages() {
        var gd = getGd();
        if (!gd || !gd._fullLayout) return;
        gd.style.position = 'relative';
        gd.style.zIndex = '0';
        gd.style.overflow = 'visible';
        var svgContainer = gd.querySelector('.svg-container');
        if (svgContainer) {
          svgContainer.style.position = 'relative';
          svgContainer.style.zIndex = '1';
        }
        var layer = getOverlay(gd);
        layer.querySelectorAll('.epaa-img-overlay').forEach(function(node) { node.remove(); });
        var fl = gd._fullLayout;
        var xa = fl.xaxis;
        var ya = fl.yaxis;
        if (!xa || !ya) return;
        var ml = fl.margin && fl.margin.l ? fl.margin.l : 0;
        var mt = fl.margin && fl.margin.t ? fl.margin.t : 0;
        var activeKey = gd._epaaActiveKey || null;
        (gd._epaaOverlayImages || []).forEach(function(d) {
          if (!d.src) return;
          var xpx = d.xmode === 'leftMargin' ? ml + d.x : ml + xa.l2p(d.x);
          var ypx = mt + ya.l2p(d.y);
          if (!isFinite(xpx) || !isFinite(ypx)) return;
          if (!isVisibleInScroll(gd, ypx, d.h)) return;
          var img = document.createElement('img');
          img.className = 'epaa-img-overlay';
          img.src = String(d.src || '').replace(/^www[/]/, '').replace(/^[/]+/, '');
          img.alt = '';
          img.loading = 'eager';
          img.decoding = 'async';
          img.dataset.key = d.key == null ? '' : String(d.key);
          img.dataset.baseOpacity = d.opacity == null ? '1' : String(d.opacity);
          img.dataset.baseZ = d.z == null ? '80' : String(d.z);
          img.onerror = function() { this.style.display = 'none'; };
          img.style.position = 'absolute';
          img.style.left = (xpx - d.w / 2) + 'px';
          img.style.top = (ypx - d.h / 2) + 'px';
          img.style.width = d.w + 'px';
          img.style.height = d.h + 'px';
          img.style.objectFit = 'contain';
          img.style.objectPosition = 'center';
          img.style.pointerEvents = 'none';
          img.style.zIndex = img.dataset.baseZ;
          img.style.opacity = img.dataset.baseOpacity;
          img.style.filter = 'none';
          img.style.transform = 'scale(1)';
          img.style.transformOrigin = 'center center';
          img.style.willChange = 'opacity, filter, transform';
          layer.appendChild(img);
        });
        shadeImages(gd, activeKey);
        suppressNativeHover(gd);
      }
      function scheduleDraw() {
        if (el._epaaDrawPending) return;
        el._epaaDrawPending = true;
        window.requestAnimationFrame(function() {
          el._epaaDrawPending = false;
          drawImages();
        });
      }
      function applyHover(gd, key, pt) {
        if (!gd) return;
        if (gd._epaaLastHoverKey === String(key || '')) {
          showTooltip(gd, pt);
          return;
        }
        gd._epaaLastHoverKey = String(key || '');
        gd._epaaActiveKey = key || null;
        shadeImages(gd, key);
        restylePlotObjects(gd, key);
        showTooltip(gd, pt);
        suppressNativeHover(gd);
      }
      var gd = getGd();
      if (gd) {
        gd._epaaOverlayImages = data.images || [];
        gd._epaaActiveKey = null;
        gd._epaaLastHoverKey = '';
      }
      setTimeout(scheduleDraw, 60);
      if (gd && gd.on) {
        // Shiny/Plotly can reuse the same graph div after filters change. Rebind
        // this widget's handlers on every render; otherwise hover behavior can
        // silently become stale after Plotly.react/newPlot.
        try {
          if (gd._epaaAfterplotHandler && gd.removeListener) gd.removeListener('plotly_afterplot', gd._epaaAfterplotHandler);
          if (gd._epaaRelayoutHandler && gd.removeListener) gd.removeListener('plotly_relayout', gd._epaaRelayoutHandler);
          if (gd._epaaHoverHandler && gd.removeListener) gd.removeListener('plotly_hover', gd._epaaHoverHandler);
          if (gd._epaaUnhoverHandler && gd.removeListener) gd.removeListener('plotly_unhover', gd._epaaUnhoverHandler);
        } catch(e) {}
        gd._epaaAfterplotHandler = function() { setTimeout(scheduleDraw, 20); };
        gd._epaaRelayoutHandler = function() { setTimeout(scheduleDraw, 20); };
        gd._epaaHoverHandler = function(evt) {
          var pt = evt && evt.points && evt.points.length ? evt.points[0] : null;
          var key = keyFromPoint(pt);
          if (el._epaaHoverPending) cancelAnimationFrame(el._epaaHoverPending);
          el._epaaHoverPending = requestAnimationFrame(function() { applyHover(gd, key, pt); });
        };
        gd._epaaUnhoverHandler = function() {
          if (el._epaaHoverPending) cancelAnimationFrame(el._epaaHoverPending);
          gd._epaaLastHoverKey = '';
          gd._epaaActiveKey = null;
          shadeImages(gd, null);
          restylePlotObjects(gd, null);
          hideTooltip(gd);
          suppressNativeHover(gd);
        };
        gd.on('plotly_afterplot', gd._epaaAfterplotHandler);
        gd.on('plotly_relayout', gd._epaaRelayoutHandler);
        gd.on('plotly_hover', gd._epaaHoverHandler);
        gd.on('plotly_unhover', gd._epaaUnhoverHandler);

        var scrollBox = gd.closest('.lb-scroll-plot');
        if (scrollBox) {
          try {
