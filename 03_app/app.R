## EPAA-per-100 draw matrix [n_draws × nrow(rows)] for the given aggregate rows.
## Linearizes each actor at their mean context logit and sweeps posterior draws
## of the random effect — identical in spirit to the CI code in §09.
.epaa_per100_draws <- function(rows, draws_by_family, sign) {
  n_draws_local <- nrow(draws_by_family[[1]])
  out <- matrix(NA_real_, nrow = n_draws_local, ncol = nrow(rows))
  for (t in 1:3) {
    sel <- which(rows$shot_type == t)
    if (!length(sel)) next
    a_draws   <- draws_by_family[[t]][, rows$idx[sel], drop = FALSE]
    me        <- rows$mean_eta[sel]
    pv        <- rows$pt_val[sel]
    base_p    <- inv_logit(me)
    skilled_p <- inv_logit(sweep(a_draws, 2, me, "+"))
    delta     <- sweep(skilled_p, 2, base_p, "-") * sign
    out[, sel] <- sweep(delta, 2, pv * 100, "*")
  }
  out
}

