    if (!identical(role, "team") && !identical(team_filter, "all") && "team_abbr" %in% names(df)) {
      df <- df[df$team_abbr == team_filter, , drop = FALSE]
    }
    if (!nrow(df)) return(NULL)

    if (metric == "total") {
      df$talent <- df$total_mid
      df$talent_lo <- df$total_q10
      df$talent_hi <- df$total_q90
    } else {
      df$talent <- df$per100_mid
      df$talent_lo <- df$per100_q10
      df$talent_hi <- df$per100_q90
    }

    attr(df, "role") <- role
    attr(df, "metric") <- metric
    attr(df, "obs_label") <- lb_meta[[role]]$obs_label
    df
  })
  
  output$sc_title <- renderText({
    role <- input$sc_role %||% "offense"
    shot <- input$sc_shot %||% "all"
    metric <- input$sc_xaxis %||% "per100"
    role_lab <- switch(role, offense = "Offensive Players",
                       defense = "Defensive Players", team = "Team Defense")
    shot_lab <- switch(shot, all = "All Shots", j3 = "3-Pointers",
                       j2 = "Mid-Range", rim = "Rim Attempts")
    metric_lab <- if (metric == "total") "Total EPAA" else "EPAA per 100"
    sprintf("%s  •  %s  •  Shot Quality vs %s", role_lab, shot_lab, metric_lab)
  })
  
  output$sc_help_text <- renderUI({
    role <- input$sc_role %||% "offense"
    metric <- input$sc_xaxis %||% "per100"
    metric_txt <- if (metric == "total") "total EPAA" else "EPAA per 100"
    msg <- switch(role,
      offense = sprintf("Upper-right players combine harder shot diets with stronger context-adjusted shot-making based on %s.", metric_txt),
      defense = sprintf("Further-right defenders prevent more expected points based on %s; higher y-values mean they faced a tougher shot mix.", metric_txt),
      team    = sprintf("Further-right teams prevent more expected points based on %s; higher y-values mean opponents generated a tougher shot mix.", metric_txt))
    tagList(
      div(msg),
      div(style = "margin-top: 6px;", "Hover any headshot or logo for observations, EPAA, and shot quality.")
    )
  })

  # output$sc_note_text <- renderUI({
  #   metric <- input$sc_xaxis %||% "per100"
  #   x_text <- if (metric == "total") "total EPAA" else "EPAA per 100 shots"
  #   div(sprintf("X-axis shows %s. Y-axis shows average context-based expected points per shot. Positive values on the x-axis indicate added offensive value or prevented defensive value, depending on the selected role.", x_text))
  # })
  
  output$scatter_plot <- renderPlotly({
    df <- scatter_data()
    validate(need(!is.null(df) && nrow(df) > 0,
                  "No players meet the current filters. Try lowering the minimum-observations threshold."))
    
    role <- attr(df, "role")
    metric <- attr(df, "metric")
    obs_label <- attr(df, "obs_label")
    metric_label <- if (metric == "total") "Total EPAA" else "EPAA per 100 Shots"
    x_title <- if (role == "offense") {
      sprintf("Shooting Talent (%s)", metric_label)
    } else {
      sprintf("Defensive Talent (%s Prevented)", metric_label)
    }
    
    x_range <- range(c(df$talent_lo, df$talent_hi, df$talent, 0), na.rm = TRUE)
    x_pad <- 0.10 * diff(x_range); if (!is.finite(x_pad) || x_pad == 0) x_pad <- 1
    x_range <- x_range + c(-x_pad, x_pad)
    y_avg <- stats::weighted.mean(df$shot_quality, w = pmax(df$n_obs, 1), na.rm = TRUE)
    y_range <- range(c(df$shot_quality, y_avg), na.rm = TRUE)
    y_pad <- 0.10 * diff(y_range); if (!is.finite(y_pad) || y_pad == 0) y_pad <- 0.05
    y_range <- y_range + c(-y_pad, y_pad)
    
    value_fmt <- "%+.1f"
    metric_hover_label <- if (metric == "total") "Total EPAA" else "EPAA per 100"
    team_vec <- if ("team_abbr" %in% names(df)) as.character(df$team_abbr) else rep("", nrow(df))
    team_vec[is.na(team_vec)] <- ""
    name_line <- if (any(nzchar(team_vec))) {
      sprintf(
        "<div style='display:flex;justify-content:space-between;gap:30px;min-width:210px;'><b>%s</b><span style='text-align:right;'>%s</span></div>",
        htmltools::htmlEscape(df$label),
        htmltools::htmlEscape(team_vec)
      )
    } else {
      sprintf("<div><b>%s</b></div>", htmltools::htmlEscape(df$label))
    }
    talent_txt <- sprintf("%+.1f", df$talent)
    ci_txt <- sprintf("[%+.1f, %+.1f]", df$talent_lo, df$talent_hi)
    sq_txt <- sprintf("%.2f", df$shot_quality)
    p_above_txt <- sprintf("%.1f%%", ci_band_positive_pct(df$talent_lo, df$talent_hi))
    df$hover <- sprintf(
      paste0(
        "%s<div style='height:8px;'></div>",
        "<table style='border-collapse:collapse;width:100%%;font-variant-numeric:tabular-nums;'>",
        "<tr><td style='padding-right:18px;'>%s</td><td style='text-align:right;'>%s</td></tr>",
        "<tr><td style='padding-right:18px;'>%s</td><td style='text-align:right;'>%s</td></tr>",
        "<tr><td style='padding-right:18px;'>80%% CI</td><td style='text-align:right;'>%s</td></tr>",
        "<tr><td style='padding-right:18px;'>P(Above Average)</td><td style='text-align:right;'>%s</td></tr>",
        "<tr><td style='padding-right:18px;'>Shot Quality</td><td style='text-align:right;'>%s xPts/shot</td></tr>",
        "</table>"
      ),
      name_line,
      obs_label, formatC(df$n_obs, format = "d", big.mark = ","),
      metric_hover_label, talent_txt,
      ci_txt,
      p_above_txt,
      sq_txt
    )
    
    point_col <- ifelse(df$talent >= 0, "#22c55e", "#ef4444")

    # Image marker sizing. For player scatterplots, scale headshot footprint by
    # shot volume so high-sample players read as more reliable / prominent while
    # still keeping the plot legible. Team logos remain a compact fixed size.
    if (role == "team") {
      df$img_w <- 32
      df$img_h <- 32
      df$hit_size <- 34
    } else {
      n_rng <- range(df$n_obs, na.rm = TRUE)
      if (!all(is.finite(n_rng)) || diff(n_rng) <= 0) {
        size_scaled <- rep(0.55, nrow(df))
      } else {
        size_scaled <- sqrt(pmax(df$n_obs - n_rng[1], 0) / diff(n_rng))
      }
      df$img_w <- 30 + 26 * size_scaled
      df$img_h <- 22 + 20 * size_scaled
      df$hit_size <- pmax(df$img_w, 34)
    }

    p <- plot_ly()
    p <- add_segments(p, x = 0, xend = 0, y = y_range[1], yend = y_range[2],
                      line = list(color = "#7c8290", dash = "dash", width = 1),
                      hoverinfo = "skip", showlegend = FALSE)
    p <- add_segments(p, x = x_range[1], xend = x_range[2], y = y_avg, yend = y_avg,
                      line = list(color = "#7c8290", dash = "dash", width = 1),
                      hoverinfo = "skip", showlegend = FALSE)
    p <- add_markers(p, x = df$talent, y = df$shot_quality,
                     marker = list(size = df$hit_size, color = point_col,
                                   opacity = 0.01,
                                   line = list(color = "#0a0a14", width = 0)),
                     text = df$hover, hoverinfo = "none",
                     customdata = as.character(df$idx), showlegend = FALSE,
                     meta = list(epaaMarkerTrace = TRUE))

    # Hover-only credible interval band. The custom image overlay updates this
    # trace on hover so the active headshot/logo remains the visual midpoint.
    p <- add_trace(
      p, x = c(NA_real_, NA_real_), y = c(NA_real_, NA_real_),
      type = "scatter", mode = "lines",
      line = list(color = "#ef4444", width = 5),
      opacity = 0, hoverinfo = "skip", showlegend = FALSE,
      meta = list(epaaActiveSegmentTraceNeg = TRUE)
    )
    p <- add_trace(
      p, x = c(NA_real_, NA_real_), y = c(NA_real_, NA_real_),
      type = "scatter", mode = "lines",
      line = list(color = "#22c55e", width = 5),
      opacity = 0, hoverinfo = "skip", showlegend = FALSE,
      meta = list(epaaActiveSegmentTracePos = TRUE)
    )
    
    has_img <- nzchar(df$img_url)
    scatter_overlay_images <- lapply(which(has_img), function(i) {
      list(src = df$img_url[i], xmode = "data", x = df$talent[i],
           y = df$shot_quality[i], w = df$img_w[i], h = df$img_h[i],
           key = as.character(df$idx[i]), lo = df$talent_lo[i], hi = df$talent_hi[i],
           color = point_col[i], opacity = 1, z = 1004)
    })

    x_span <- diff(x_range)
    y_span <- diff(y_range)
    qx_left  <- x_range[1] + 0.11 * x_span
    qx_right <- x_range[2] - 0.11 * x_span
    qy_low   <- y_range[1] + 0.11 * y_span
    qy_high  <- y_range[2] - 0.11 * y_span
    quad <- if (identical(role, "offense")) {
      c("Easier Shots,<br>Worse Shot-Making",
        "Easier Shots,<br>Better Shot-Making",
        "Tougher Shots,<br>Worse Shot-Making",
        "Tougher Shots,<br>Better Shot-Making")
    } else {
      c("Easier Shots Contested,<br>Worse Defense",
        "Easier Shots Contested,<br>Better Defense",
        "Tougher Shots Contested,<br>Worse Defense",
        "Tougher Shots Contested,<br>Better Defense")
    }
    quadrant_annotations <- list(
      list(x = qx_left,  y = qy_high, xref = "x", yref = "y",
           text = quad[1], showarrow = FALSE,
           font = list(color = "#a9adba", size = 14), bgcolor = "rgba(15,15,26,0.78)",
           bordercolor = "#1a1a2a", borderpad = 4),
      list(x = qx_right, y = qy_high, xref = "x", yref = "y",
           text = quad[2], showarrow = FALSE,
           font = list(color = "#a9adba", size = 14), bgcolor = "rgba(15,15,26,0.78)",
           bordercolor = "#1a1a2a", borderpad = 4),
      list(x = qx_left,  y = qy_low, xref = "x", yref = "y",
           text = quad[3], showarrow = FALSE,
           font = list(color = "#a9adba", size = 14), bgcolor = "rgba(15,15,26,0.78)",
           bordercolor = "#1a1a2a", borderpad = 4),
      list(x = qx_right, y = qy_low, xref = "x", yref = "y",
           text = quad[4], showarrow = FALSE,
           font = list(color = "#a9adba", size = 14), bgcolor = "rgba(15,15,26,0.78)",
           bordercolor = "#1a1a2a", borderpad = 4),
      list(x = -0.125, y = 0.50, xref = "paper", yref = "paper",
           text = "Better Shot Quality ─────▶", showarrow = FALSE,
           textangle = -90,
           font = list(color = "#8f95a3", size = 15)),
      list(x = 0.50, y = -0.152, xref = "paper", yref = "paper",
           text = "Better Shooting Talent ─────▶", showarrow = FALSE,
           font = list(color = "#8f95a3", size = 15))
    )

    p <- p %>%
      layout(
        images = list(),
        xaxis = list(title = list(text = x_title, font = list(color = "#a9adba", size = 16), standoff = 12),
                     range = x_range, zeroline = FALSE, gridcolor = "#1a1a2a",
                     tickfont = list(color = "#a9adba", size = 14),
                     tickformat = ".1f"),
        yaxis = list(title = list(text = "Shot Quality (Expected Points per Shot)",
                                  font = list(color = "#a9adba", size = 16), standoff = 14),
                     range = y_range, zeroline = FALSE, gridcolor = "#1a1a2a",
                     tickfont = list(color = "#a9adba", size = 14), tickformat = ".2f"),
        margin = list(l = 165, r = 35, t = 10, b = 112),
        annotations = quadrant_annotations,
        paper_bgcolor = "rgba(0,0,0,0)", plot_bgcolor = "rgba(0,0,0,0)",
        font = list(family = "Inter", color = "#cfd2dc"),
        hoverlabel = list(bgcolor = "#0a0a14", bordercolor = "#6d28d9",
                          font = list(color = "#e8e8ef", size = 13)),
        autosize = TRUE
      ) %>%
      config(displayModeBar = FALSE, responsive = TRUE)

    add_plotly_image_overlays(p, scatter_overlay_images)
  })
