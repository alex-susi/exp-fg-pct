inv_logit <- function(x) 1 / (1 + exp(-x))

ci_band_positive_pct <- function(lo, hi) {
  lo <- as.numeric(lo)
  hi <- as.numeric(hi)
  width <- hi - lo
  out <- rep(NA_real_, length(lo))
  valid <- is.finite(lo) & is.finite(hi) & is.finite(width) & width > 0
  if (any(valid)) {
    pos_width <- pmax(0, hi[valid]) - pmax(0, lo[valid])
    out[valid] <- 100 * pmin(pmax(pos_width / width[valid], 0), 1)
  }
  out
}
`%||%` <- function(x, y) if (is.null(x) || length(x) == 0) y else x

# Shiny serves files inside ./www from the app web root. Static image URLs
# should be "epaa_img_cache/...", not "www/epaa_img_cache/...". The explicit
# resource path below makes the image cache robust when launching app_v11.R as a
# single file from the 03_app directory.
register_epaa_image_cache <- function() {
  cache_dir <- file.path("www", "epaa_img_cache")
  if (!dir.exists(cache_dir)) return(invisible(FALSE))
  tryCatch(
    shiny::addResourcePath(
      "epaa_img_cache",
      normalizePath(cache_dir, winslash = "/", mustWork = FALSE)
    ),
    error = function(e) invisible(FALSE),
    warning = function(w) invisible(FALSE)
  )
  invisible(TRUE)
}
register_epaa_image_cache()

normalize_media_url_app <- function(x) {
  x <- as.character(x)
  x[is.na(x)] <- ""
  x <- gsub("\\\\", "/", x)
  x <- sub("^\\./", "", x)
  x <- sub("^/+", "", x)
  x <- sub("^www/", "", x)
  x
}

