         player_id_int, ".png")
}

resolve_cached_media_url_app <- function(url, media_type = c("headshot", "team_logo"), abbr = NA_character_) {
  media_type <- match.arg(media_type)
  u <- normalize_media_url_app(url)
  out <- u
  remote <- grepl("^https?://", out)
  local_ok <- nzchar(out) & !remote & file.exists(file.path("www", out))
  needs_fallback <- nzchar(out) & !remote & !local_ok

  if (any(needs_fallback)) {
    if (media_type == "headshot") {
      player_id <- tools::file_path_sans_ext(basename(out[needs_fallback]))
      good <- nzchar(player_id)
      repl <- rep("", length(player_id))
      repl[good] <- paste0("https://cdn.nba.com/headshots/nba/latest/260x190/", player_id[good], ".png")
      out[needs_fallback] <- repl
    } else {
      ab <- as.character(abbr)
      ab <- rep(ab, length.out = length(out))
      ab[is.na(ab) | !nzchar(ab)] <- tools::file_path_sans_ext(basename(out))[is.na(ab) | !nzchar(ab)]
      repl <- vapply(ab[needs_fallback], get_team_logo_url, character(1))
      out[needs_fallback] <- repl
    }
  }
  out[is.na(out)] <- ""
  out
}


# Precompute the leaderboard/scatterplot summaries once. This shifts the expensive
# posterior aggregation out of filter changes, so UI interactions only filter and
# sort a cached table.
summarise_draws_for_cache <- function(draw_mat, prefix) {
  stats_df <- data.frame(
    mid = colMeans(draw_mat),
    q10 = apply(draw_mat, 2, quantile, probs = 0.10, names = FALSE),
    q90 = apply(draw_mat, 2, quantile, probs = 0.90, names = FALSE),
    q25 = apply(draw_mat, 2, quantile, probs = 0.25, names = FALSE),
    q75 = apply(draw_mat, 2, quantile, probs = 0.75, names = FALSE),
    q40 = apply(draw_mat, 2, quantile, probs = 0.40, names = FALSE),
    q60 = apply(draw_mat, 2, quantile, probs = 0.60, names = FALSE),
    check.names = FALSE
  )
  names(stats_df) <- paste0(prefix, "_", names(stats_df))
  stats_df
}

build_role_shot_cache <- function(role, shot) {
  meta <- lb_meta[[role]]
  if (is.null(meta$draws)) {
    pd <- load_posterior_draws()
    meta$draws <- switch(role,
      offense = pd$player_draws,
      defense = pd$defender_draws,
      team = pd$defteam_draws
    )
  }
  n_draws_local <- nrow(meta$draws[[1]])
  agg <- lb_agg[[role]]
  fam_t <- c(rim = 1L, j2 = 2L, j3 = 3L)
  if (is.null(agg) || !nrow(agg)) return(data.frame())

  if (shot == "all") {
    rows_all <- agg
    per100_by_row <- .epaa_per100_draws(rows_all, meta$draws, meta$sign)
    total_by_row <- sweep(per100_by_row, 2, rows_all$n_obs / 100, "*")
    idx_vec <- sort(unique(rows_all$idx))

    total_draws <- vapply(idx_vec, function(i) {
      cols <- which(rows_all$idx == i)
      rowSums(total_by_row[, cols, drop = FALSE])
    }, numeric(n_draws_local))
    if (is.null(dim(total_draws))) total_draws <- matrix(total_draws, nrow = n_draws_local)

    nobs_vec <- vapply(idx_vec, function(i) sum(rows_all$n_obs[rows_all$idx == i]), integer(1))
    per100_draws <- sweep(total_draws, 2, 100 / pmax(nobs_vec, 1), "*")
    shot_quality <- vapply(idx_vec, function(i) {
      rows_i <- rows_all[rows_all$idx == i, , drop = FALSE]
      stats::weighted.mean(inv_logit(rows_i$mean_eta) * rows_i$pt_val, rows_i$n_obs)
    }, numeric(1))
  } else {
    t <- fam_t[[shot]]
    rows <- agg[agg$shot_type == t, , drop = FALSE]
    if (!nrow(rows)) return(data.frame())
    idx_vec <- rows$idx
    nobs_vec <- rows$n_obs
    per100_draws <- .epaa_per100_draws(rows, meta$draws, meta$sign)
    total_draws <- sweep(per100_draws, 2, rows$n_obs / 100, "*")
    shot_quality <- inv_logit(rows$mean_eta) * rows$pt_val
  }

  out <- data.frame(
    idx = idx_vec,
    n_obs = as.integer(nobs_vec),
    shot_quality = as.numeric(shot_quality),
    stringsAsFactors = FALSE
  )
  out <- cbind(out,
               summarise_draws_for_cache(total_draws, "total"),
               summarise_draws_for_cache(per100_draws, "per100"))
  out$label <- unname(meta$name_map[as.character(out$idx)])
  out <- out[!is.na(out$label), , drop = FALSE]

  # Media fields are normally attached from lb_cache$media_lookup. These fallback
  # fields only matter when lb_cache.rds has not been built.
  if (meta$kind == "team") {
    out$img_url <- vapply(meta$id_map[as.character(out$idx)], get_team_logo_url, character(1))
    out$team_abbr <- unname(meta$id_map[as.character(out$idx)])
    out$team_logo_url <- ""
  } else {
    out$img_url <- vapply(meta$id_map[as.character(out$idx)], get_headshot_url, character(1))
    if (role == "offense") {
      out$team_abbr <- unname(player_team_link[as.character(out$idx)])
      out$team_logo_url <- unname(player_team_logo_lookup[as.character(out$idx)])
    } else {
      out$team_abbr <- unname(defender_team_abbr_lookup[as.character(out$idx)])
      out$team_logo_url <- unname(defender_team_logo_lookup[as.character(out$idx)])
    }
  }
  out$img_url[is.na(out$img_url)] <- ""
  out$team_abbr[is.na(out$team_abbr)] <- ""
  out$team_logo_url[is.na(out$team_logo_url)] <- ""
  out
}

