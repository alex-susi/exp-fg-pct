load_posterior_draws <- function() {
  if (exists("draws", envir = posterior_draws_env, inherits = FALSE)) {
    return(get("draws", envir = posterior_draws_env, inherits = FALSE))
  }

  if (!is.na(draws_app_path)) {
    d <- readRDS(draws_app_path)
    d$n_draws <- d$n_draws %||% nrow(d$cal_draws)
  } else {
    draws_mat <- readRDS(file.path("draws_mat.rds"))
    d <- list()
    d$n_draws <- nrow(draws_mat)
    d$cal_draws <- as.matrix(draws_mat[, c(paste0("cal_intercept[", 1:3, "]"),
                                           paste0("cal_slope[", 1:3, "]")), drop = FALSE])
    Jp <- max(as.integer(gsub(".*\\[(\\d+),.*", "\\1",
                              grep("^a_player\\[", colnames(draws_mat), value = TRUE))))
    Jd <- max(as.integer(gsub(".*\\[(\\d+),.*", "\\1",
                              grep("^a_defender\\[", colnames(draws_mat), value = TRUE))))
    Jt <- max(as.integer(gsub(".*\\[(\\d+),.*", "\\1",
                              grep("^a_defteam\\[", colnames(draws_mat), value = TRUE))))
    extract_re <- function(prefix, J) {
      lapply(1:3, function(t) {
        as.matrix(draws_mat[, paste0(prefix, "[", 1:J, ",", t, "]"), drop = FALSE])
      })
    }
    d$player_draws <- extract_re("a_player", Jp)
    d$defender_draws <- extract_re("a_defender", Jd)
    d$defteam_draws <- extract_re("a_defteam", Jt)
    rm(draws_mat)
    invisible(gc())
  }

  d$J_player <- ncol(d$player_draws[[1]])
  d$J_defender <- ncol(d$defender_draws[[1]])
  d$J_defteam <- ncol(d$defteam_draws[[1]])
  assign("draws", d, envir = posterior_draws_env)
  d
}

