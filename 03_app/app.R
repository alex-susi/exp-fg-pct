## ═══════════════════════════════════════════════════════════════════════════════
## LEADERBOARD PRECOMPUTATION ==================================================
## ═══════════════════════════════════════════════════════════════════════════════
## For every actor (shooter / individual defender / defensive team) and shot
## family we precompute the mean context logit (eta_context) and observation
## count. These feed the same per-draw EPAA computation used in
## 03_shootingTalent.R (§09): EPAA_per100 = 100 × (p_skill − p_context) × pts,
## evaluated at the actor's mean context and swept across posterior draws of the
## relevant random effect. Offense adds points (sign +1); defense/team prevent
## points (sign −1, so a negative a_defender → positive EPAA).

cat("Loading/precomputing leaderboard aggregates...\n")

if (!is.null(shots_summary) && !is.null(shots_summary$lb_agg)) {
  lb_agg <- shots_summary$lb_agg
} else {
  # Posterior-mean calibration params (per shot family) → context logit per shot
  cal_hat_intercept <- colMeans(cal_draws[, 1:3, drop = FALSE])
  cal_hat_slope     <- colMeans(cal_draws[, 4:6, drop = FALSE])

  shots$eta_context <- cal_hat_intercept[shots$shot_type] +
                       cal_hat_slope[shots$shot_type] * shots$xfg_logit
  shots$point_value <- ifelse(shots$shot_type == 3, 3, 2)

  # Aggregate context + counts by (actor, shot family). Returns one row per
  # (idx, shot_type) with mean_eta, n_obs, pt_val.
  .agg_actor_family <- function(df, id_col) {
    df <- df[!is.na(df[[id_col]]), c(id_col, "shot_type", "eta_context",
                                     "point_value")]
    if (!nrow(df)) return(data.frame(idx = integer(0), shot_type = integer(0),
                                     n_obs = integer(0), mean_eta = numeric(0),
                                     pt_val = numeric(0)))
    g <- interaction(df[[id_col]], df$shot_type, drop = TRUE)
    data.frame(
      idx       = as.integer(tapply(df[[id_col]],    g, function(x) x[1])),
      shot_type = as.integer(tapply(df$shot_type,    g, function(x) x[1])),
      n_obs     = as.integer(tapply(df$shot_type,    g, length)),
      mean_eta  = as.numeric(tapply(df$eta_context,  g, mean)),
      pt_val    = as.numeric(tapply(df$point_value,  g, function(x) x[1])),
      row.names = NULL
    )
  }

  lb_agg <- list(
    offense = .agg_actor_family(shots, "player_idx"),
    defense = .agg_actor_family(shots, "defender_idx"),
    team    = .agg_actor_family(shots, "defteam_idx")
  )
}

